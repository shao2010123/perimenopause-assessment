function getReferenceSortKey(id) {
  const matched = id.match(/^R(\d+)([a-z]*)$/i);
  if (!matched) return { numeric: 0, suffix: id };

  return {
    numeric: Number(matched[1]),
    suffix: matched[2] ?? '',
  };
}

export function getRefsByModule(moduleName) {
  return Object.values(references).filter((reference) => reference.modules?.includes(moduleName));
}

export function getCoreRefs() {
  return ['R1', 'R4', 'R39', 'R40', 'R41', 'R42'].map((id) => references[id]);
}

export function getAllRefsForPDF() {
  return Object.values(references).sort((left, right) => {
    const keyA = getReferenceSortKey(left.id);
    const keyB = getReferenceSortKey(right.id);

    if (keyA.numeric !== keyB.numeric) return keyA.numeric - keyB.numeric;
    return keyA.suffix.localeCompare(keyB.suffix, 'en');
  });
}

